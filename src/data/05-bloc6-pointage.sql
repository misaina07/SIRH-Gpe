-- Bloc 6 / MIRADO : pointage, feuilles de temps, horaires configurables,
-- régularisations, choix de récupération et variables pour l'export de paie.
-- À appliquer après 03-bloc5-misaina.sql et 04-bloc5-dossier-complet.sql.
BEGIN;

-- Les anciens horodatages sont des heures murales françaises des fixtures.
DO $$ BEGIN
    IF (SELECT data_type FROM information_schema.columns
        WHERE table_schema='public' AND table_name='time_clock_events' AND column_name='event_timestamp')
        = 'timestamp without time zone' THEN
        ALTER TABLE time_clock_events
            ALTER COLUMN event_timestamp TYPE TIMESTAMPTZ
            USING event_timestamp AT TIME ZONE 'Europe/Paris';
    END IF;
END $$;
ALTER TABLE time_clock_events
    ADD COLUMN IF NOT EXISTS recorded_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS idempotency_key UUID,
    ADD COLUMN IF NOT EXISTS is_regularized BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS regularization_reason VARCHAR(500);
UPDATE time_clock_events SET recorded_at=event_timestamp WHERE recorded_at IS NULL;
ALTER TABLE time_clock_events ALTER COLUMN recorded_at SET DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE time_clock_events ALTER COLUMN recorded_at SET NOT NULL;
ALTER TABLE time_clock_events DROP CONSTRAINT IF EXISTS time_clock_events_event_type_check;
ALTER TABLE time_clock_events ADD CONSTRAINT time_clock_events_event_type_check
    CHECK (event_type IN ('IN','BREAK','RESUME','OUT'));
CREATE UNIQUE INDEX IF NOT EXISTS ux_time_clock_events_idempotency
    ON time_clock_events(employee_id,idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_time_clock_events_employee_instant
    ON time_clock_events(employee_id,event_timestamp,id);

-- Les anciennes tables ont parfois un identifiant sans séquence.
DO $$ BEGIN
    IF pg_get_serial_sequence('time_clock_events','id') IS NULL THEN
        ALTER TABLE time_clock_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF pg_get_serial_sequence('daily_time_sheets','id') IS NULL THEN
        ALTER TABLE daily_time_sheets ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;
SELECT setval(pg_get_serial_sequence('time_clock_events','id'),
    GREATEST(COALESCE((SELECT max(id) FROM time_clock_events),0)+1,1),false);
SELECT setval(pg_get_serial_sequence('daily_time_sheets','id'),
    GREATEST(COALESCE((SELECT max(id) FROM daily_time_sheets),0)+1,1),false);

ALTER TABLE daily_time_sheets
    ADD COLUMN IF NOT EXISTS pause_minutes INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS overtime_25_minutes INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS overtime_50_minutes INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS regular_work_minutes INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS first_in TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS last_out TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS anomaly_codes TEXT[] NOT NULL DEFAULT '{}',
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS approved_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;
UPDATE daily_time_sheets SET regular_work_minutes=effective_worked_minutes
WHERE regular_work_minutes=0 AND effective_worked_minutes>0;
UPDATE daily_time_sheets SET overtime_25_minutes=overtime_minutes
WHERE overtime_25_minutes=0 AND overtime_minutes>0;
ALTER TABLE daily_time_sheets DROP CONSTRAINT IF EXISTS daily_time_sheets_status_check;
ALTER TABLE daily_time_sheets ADD CONSTRAINT daily_time_sheets_status_check
    CHECK (status IN ('soumis','valide','corrige','valide_manager','rejete','cloture_paie'));

CREATE TABLE IF NOT EXISTS employee_work_schedules (
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    iso_weekday SMALLINT NOT NULL CHECK (iso_weekday BETWEEN 1 AND 7),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    remote BOOLEAN NOT NULL DEFAULT FALSE,
    on_call BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(employee_id,iso_weekday),
    CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS time_regularization_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    requested_by VARCHAR(20) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_type VARCHAR(10) NOT NULL CHECK (event_type IN ('IN','BREAK','RESUME','OUT')),
    requested_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'en_attente'
        CHECK (status IN ('en_attente','approuvee','refusee')),
    reviewed_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    decision_note VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_time_regularization_queue
    ON time_regularization_requests(status,created_at DESC);

CREATE TABLE IF NOT EXISTS time_overtime_preferences (
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    week_start DATE NOT NULL,
    preference VARCHAR(10) NOT NULL CHECK (preference IN ('PAIEMENT','CET')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(employee_id,week_start)
);

CREATE TABLE IF NOT EXISTS time_on_call_premiums (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    work_date DATE NOT NULL,
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'EUR',
    reason VARCHAR(300) NOT NULL,
    recorded_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_time_on_call_premiums_month
    ON time_on_call_premiums(work_date,employee_id);

UPDATE users
SET allowed_views=array_append(COALESCE(allowed_views,'{}'),'pointage')
WHERE role_type IN ('RH','Manager','Employee')
  AND NOT ('pointage'=ANY(COALESCE(allowed_views,'{}')));

COMMIT;
