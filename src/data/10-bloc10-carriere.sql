-- Bloc 10 / Carriere et mobilite
BEGIN;

CREATE TABLE IF NOT EXISTS historique_affectation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  department_id VARCHAR(50) REFERENCES departments(id),
  poste VARCHAR(150) NOT NULL,
  manager_id VARCHAR(20) REFERENCES users(id),
  date_debut DATE NOT NULL,
  date_fin DATE,
  CHECK(date_fin IS NULL OR date_fin >= date_debut)
);

CREATE TABLE IF NOT EXISTS promotion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  ancien_grade VARCHAR(30),
  nouveau_grade VARCHAR(30) NOT NULL,
  date_effet DATE NOT NULL,
  statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON',
  commentaire TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mutation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  ancien_departement VARCHAR(50),
  nouveau_departement VARCHAR(50) NOT NULL,
  ancien_poste VARCHAR(150),
  nouveau_poste VARCHAR(150) NOT NULL,
  date_effet DATE NOT NULL,
  statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON',
  commentaire TEXT
);

CREATE TABLE IF NOT EXISTS historique_salaire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  salaire_mensuel NUMERIC(14,2) NOT NULL,
  date_debut DATE NOT NULL,
  date_fin DATE,
  motif VARCHAR(100),
  CHECK(date_fin IS NULL OR date_fin >= date_debut)
);

CREATE INDEX IF NOT EXISTS idx_affectation_employee_dates ON historique_affectation(employee_id,date_debut,date_fin);
CREATE INDEX IF NOT EXISTS idx_salaire_employee_dates ON historique_salaire(employee_id,date_debut,date_fin);
COMMIT;
