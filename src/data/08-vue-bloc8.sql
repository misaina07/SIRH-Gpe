CREATE TABLE IF NOT EXISTS bulletin_paie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periode_id INTEGER NOT NULL REFERENCES periode_paie(id) ON DELETE RESTRICT,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    salaire_brut NUMERIC(14,2) NOT NULL,
    cnaps_salarie NUMERIC(14,2) NOT NULL,
    ostie_salarie NUMERIC(14,2) NOT NULL,
    base_imposable NUMERIC(14,2) NOT NULL,
    irsa NUMERIC(14,2) NOT NULL,
    net_a_payer NUMERIC(14,2) NOT NULL,
    UNIQUE(periode_id,employee_id)
);

CREATE TABLE IF NOT EXISTS ligne_bulletin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bulletin_id BIGINT NOT NULL REFERENCES bulletin_paie(id) ON DELETE CASCADE,
    rubrique_code VARCHAR(20) NOT NULL REFERENCES rubrique_paie(code) ON DELETE RESTRICT,
    quantite NUMERIC(10,2),
    taux NUMERIC(14,4),
    montant NUMERIC(14,2) NOT NULL
);

-- Vues de collecte : chaque domaine reste isolé et testable.
CREATE OR REPLACE VIEW v_payroll_contract AS
SELECT DISTINCT ON (ec.employee_id)
       ec.employee_id,
       ec.monthly_gross_salary,
       ec.fixed_bonus,
       ec.variable_bonus,
       ec.work_regime,
       ec.grade,
       ec.start_date,
       ec.end_date
FROM employee_contracts ec
ORDER BY ec.employee_id,ec.start_date DESC,ec.id DESC;

CREATE OR REPLACE VIEW v_payroll_employee_contract AS
SELECT e.id,e.matricule,e.first_name,e.last_name,
       c.monthly_gross_salary,c.fixed_bonus,c.variable_bonus,
       c.work_regime,c.grade,c.start_date,c.end_date
FROM employees e
LEFT JOIN v_payroll_contract c ON c.employee_id=e.id
WHERE e.status='actif';

CREATE OR REPLACE VIEW v_payroll_time_entries AS
SELECT employee_id,work_date,
       effective_worked_minutes,overtime_25_minutes,overtime_50_minutes,
       regular_work_minutes,pause_minutes,first_in,last_out,status
FROM daily_time_sheets;

CREATE OR REPLACE VIEW v_payroll_leave_entries AS
SELECT r.employee_id,r.leave_type_id,r.start_date,r.end_date,
       r.total_business_days,r.status,lt.requires_balance
FROM leave_requests r
JOIN leave_types lt ON lt.id=r.leave_type_id;

CREATE OR REPLACE VIEW v_payroll_manual_variables AS
SELECT v.employee_id,p.date_debut,p.date_fin,
       v.rubrique_code,v.quantite,v.montant,v.semaine,
       r.libelle,r.type
FROM variable_paie v
JOIN periode_paie p ON p.id=v.periode_id
JOIN rubrique_paie r ON r.code=v.rubrique_code;

