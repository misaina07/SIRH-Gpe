BEGIN;

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_type_check;
ALTER TABLE users ADD CONSTRAINT users_role_type_check
    CHECK (role_type IN ('RH', 'Manager', 'Finance', 'Direction', 'Employee'));
UPDATE users
SET allowed_views = array_append(allowed_views, 'employes-contrats')
WHERE role_type='RH' AND NOT ('employes-contrats'=ANY(allowed_views));

ALTER TABLE employees
    ADD COLUMN IF NOT EXISTS source_candidate_id VARCHAR(30),
    ADD COLUMN IF NOT EXISTS nationality VARCHAR(80),
    ADD COLUMN IF NOT EXISTS national_id_encrypted TEXT,
    ADD COLUMN IF NOT EXISTS address_street VARCHAR(255),
    ADD COLUMN IF NOT EXISTS address_city VARCHAR(100),
    ADD COLUMN IF NOT EXISTS address_zip VARCHAR(12),
    ADD COLUMN IF NOT EXISTS emergency_contact_name VARCHAR(150),
    ADD COLUMN IF NOT EXISTS emergency_contact_phone VARCHAR(50);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='employees_source_candidate_fk') THEN
        ALTER TABLE employees ADD CONSTRAINT employees_source_candidate_fk
            FOREIGN KEY (source_candidate_id) REFERENCES candidates(id) ON DELETE RESTRICT;
    END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS ux_employees_source_candidate
    ON employees(source_candidate_id) WHERE source_candidate_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS employee_contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    contract_type VARCHAR(30) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    trial_period_end DATE,
    grade VARCHAR(10) NOT NULL,
    coefficient VARCHAR(30),
    job_title VARCHAR(150) NOT NULL,
    work_regime VARCHAR(30) NOT NULL,
    work_percentage NUMERIC(5,2) NOT NULL DEFAULT 100,
    is_executive BOOLEAN NOT NULL DEFAULT FALSE,
    monthly_gross_salary NUMERIC(10,2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date IS NULL OR end_date >= start_date),
    CHECK (work_percentage > 0 AND work_percentage <= 100),
    CHECK (monthly_gross_salary > 0)
);
CREATE INDEX IF NOT EXISTS idx_employee_contracts_employee_dates
    ON employee_contracts(employee_id, start_date DESC);

ALTER TABLE employee_documents
    ADD COLUMN IF NOT EXISTS filename VARCHAR(255),
    ADD COLUMN IF NOT EXISTS verification_status VARCHAR(30) NOT NULL DEFAULT 'en_attente',
    ADD COLUMN IF NOT EXISTS verified_by VARCHAR(20),
    ADD COLUMN IF NOT EXISTS verified_at TIMESTAMP;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='employee_documents_verified_by_fk') THEN
        ALTER TABLE employee_documents ADD CONSTRAINT employee_documents_verified_by_fk
            FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='employee_documents_verification_status_check') THEN
        ALTER TABLE employee_documents ADD CONSTRAINT employee_documents_verification_status_check
            CHECK (verification_status IN ('en_attente','valide','rejete','expire'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS employee_career_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    event_type VARCHAR(50) NOT NULL,
    event_date DATE NOT NULL,
    title VARCHAR(180) NOT NULL,
    description TEXT,
    created_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_employee_career_events_employee_date
    ON employee_career_events(employee_id, event_date DESC, id DESC);

CREATE TABLE IF NOT EXISTS gdpr_access_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    employee_id INT REFERENCES employees(id) ON DELETE SET NULL,
    action VARCHAR(40) NOT NULL,
    data_category VARCHAR(50) NOT NULL,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_gdpr_access_audit_employee_time
    ON gdpr_access_audit(employee_id, occurred_at DESC);

COMMIT;
