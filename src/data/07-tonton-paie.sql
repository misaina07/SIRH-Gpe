CREATE TABLE IF NOT EXISTS payroll_monthly_variables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    period_month DATE NOT NULL CHECK (period_month = date_trunc('month', period_month)::date),
    overtime_25_minutes INT NOT NULL DEFAULT 0 CHECK (overtime_25_minutes >= 0),
    overtime_50_minutes INT NOT NULL DEFAULT 0 CHECK (overtime_50_minutes >= 0),
    unpaid_absence_days NUMERIC(6,2) NOT NULL DEFAULT 0 CHECK (unpaid_absence_days >= 0),
    on_call_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (on_call_amount >= 0),
    overtime_preference VARCHAR(10) NOT NULL DEFAULT 'PAIEMENT'
        CHECK (overtime_preference IN ('PAIEMENT','CET')),
    generated_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(employee_id, period_month)
);
CREATE INDEX IF NOT EXISTS idx_payroll_monthly_variables_period
    ON payroll_monthly_variables(period_month, employee_id);

CREATE TABLE IF NOT EXISTS payroll_export_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_month DATE NOT NULL CHECK (period_month = date_trunc('month', period_month)::date),
    export_format VARCHAR(10) NOT NULL CHECK (export_format IN ('CSV','XLSX')),
    row_count INT NOT NULL CHECK (row_count >= 0),
    sha256 VARCHAR(64) NOT NULL,
    generated_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_payroll_export_runs_period
    ON payroll_export_runs(period_month, generated_at DESC);

COMMIT;
