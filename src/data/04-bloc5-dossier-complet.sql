-- Complements applicatifs du dossier salarié (GED, avantages, demandes personnelles et conservation).
-- À appliquer après 03-bloc5-misaina.sql. Migration additive.
BEGIN;

-- Le portail employé dispose d'une autorité dédiée aux données personnelles.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_type_check;
ALTER TABLE users ADD CONSTRAINT users_role_type_check
    CHECK (role_type IN ('RH', 'Manager', 'Finance', 'Direction', 'Employee'));
UPDATE users
SET allowed_views = array_append(allowed_views, 'employes-contrats')
WHERE role_type IN ('RH','Manager','Direction','Employee')
  AND NOT ('employes-contrats'=ANY(allowed_views));

ALTER TABLE employees
    ADD COLUMN IF NOT EXISTS email_perso VARCHAR(150),
    ADD COLUMN IF NOT EXISTS rib_encrypted TEXT,
    ADD COLUMN IF NOT EXISTS office_location VARCHAR(150),
    ADD COLUMN IF NOT EXISTS telework_days TEXT[] NOT NULL DEFAULT '{}',
    ADD COLUMN IF NOT EXISTS skills TEXT[] NOT NULL DEFAULT '{}',
    ADD COLUMN IF NOT EXISTS exit_date DATE,
    ADD COLUMN IF NOT EXISTS anonymized_at TIMESTAMP;
CREATE UNIQUE INDEX IF NOT EXISTS ux_employees_user_id
    ON employees(user_id) WHERE user_id IS NOT NULL;

ALTER TABLE employee_contracts
    ADD COLUMN IF NOT EXISTS probation_renewal_date DATE,
    ADD COLUMN IF NOT EXISTS coefficient VARCHAR(30),
    ADD COLUMN IF NOT EXISTS fixed_bonus NUMERIC(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS variable_bonus NUMERIC(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS company_vehicle BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS company_health_plan BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS meal_vouchers BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE employee_documents
    ADD COLUMN IF NOT EXISTS mime_type VARCHAR(100),
    ADD COLUMN IF NOT EXISTS file_size_bytes BIGINT,
    ADD COLUMN IF NOT EXISTS encrypted_content BYTEA,
    ADD COLUMN IF NOT EXISTS uploaded_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS verification_note TEXT,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS employee_change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    requested_by VARCHAR(20) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    encrypted_payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'en_attente'
        CHECK (status IN ('en_attente','approuvee','refusee')),
    reviewed_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMP,
    decision_note VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_employee_change_requests_pending
    ON employee_change_requests(status, created_at DESC);

CREATE TABLE IF NOT EXISTS employee_document_expiry_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id INT NOT NULL REFERENCES employee_documents(id) ON DELETE CASCADE,
    employee_id INT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    expiration_date DATE NOT NULL,
    days_before SMALLINT NOT NULL CHECK (days_before IN (30,7,0)),
    emitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(document_id, expiration_date, days_before)
);
ALTER TABLE employee_document_expiry_notifications
    ADD COLUMN IF NOT EXISTS expiration_date DATE;
UPDATE employee_document_expiry_notifications n
SET expiration_date=d.expiration_date
FROM employee_documents d
WHERE n.document_id=d.id AND n.expiration_date IS NULL;
ALTER TABLE employee_document_expiry_notifications ALTER COLUMN expiration_date SET NOT NULL;
ALTER TABLE employee_document_expiry_notifications
    DROP CONSTRAINT IF EXISTS employee_document_expiry_notificati_document_id_days_before_key;
CREATE UNIQUE INDEX IF NOT EXISTS ux_employee_document_expiry_notifications_cycle
    ON employee_document_expiry_notifications(document_id, expiration_date, days_before);
CREATE INDEX IF NOT EXISTS idx_employee_document_expiry_notifications_time
    ON employee_document_expiry_notifications(emitted_at DESC);

-- Aucune durée n'est imposée par le code : le responsable de traitement configure les catégories.
CREATE TABLE IF NOT EXISTS employee_retention_policies (
    data_category VARCHAR(50) PRIMARY KEY,
    retention_days INT NOT NULL CHECK (retention_days > 0),
    updated_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
