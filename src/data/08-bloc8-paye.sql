CREATE TABLE IF NOT EXISTS secteur (
    id SERIAL PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    libelle VARCHAR(100) NOT NULL,
    diviseur_horaire NUMERIC(6,2) NOT NULL CHECK(diviseur_horaire>0)
);

CREATE TABLE IF NOT EXISTS categorie_professionnelle (
    id SERIAL PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    libelle VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS parametre_legal (
    id SERIAL PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    secteur_id INTEGER REFERENCES secteur(id),
    valeur NUMERIC(14,4) NOT NULL,
    date_effet DATE NOT NULL,
    statut VARCHAR(12) NOT NULL DEFAULT 'EN_VIGUEUR'
        CHECK(statut IN ('EN_VIGUEUR','PROJET'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_parametre_legal
    ON parametre_legal(code,COALESCE(secteur_id,0),date_effet);

CREATE TABLE IF NOT EXISTS bareme_irsa (
    id SERIAL PRIMARY KEY,
    date_effet DATE NOT NULL,
    borne_basse NUMERIC(14,2) NOT NULL,
    borne_haute NUMERIC(14,2),
    taux NUMERIC(7,4) NOT NULL CHECK(taux>=0 AND taux<1),
    UNIQUE(date_effet,borne_basse)
);

CREATE TABLE IF NOT EXISTS periode_paie (
    id SERIAL PRIMARY KEY,
    annee INTEGER NOT NULL,
    mois INTEGER NOT NULL CHECK(mois BETWEEN 1 AND 12),
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL CHECK(date_fin>=date_debut),
    verrouillee BOOLEAN NOT NULL DEFAULT FALSE,
    statut VARCHAR(20) NOT NULL DEFAULT 'OUVERT'
        CHECK(statut IN ('OUVERT','VERIFIE','VERROUILLE')),
    UNIQUE(annee,mois)
);

CREATE TABLE IF NOT EXISTS rubrique_paie (
    id SERIAL PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    libelle VARCHAR(100) NOT NULL,
    type VARCHAR(10) NOT NULL CHECK(type IN ('GAIN','RETENUE'))
);

CREATE TABLE IF NOT EXISTS variable_paie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periode_id INTEGER NOT NULL REFERENCES periode_paie(id) ON DELETE RESTRICT,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    rubrique_code VARCHAR(20) NOT NULL REFERENCES rubrique_paie(code) ON DELETE RESTRICT,
    quantite NUMERIC(10,2) NOT NULL DEFAULT 0,
    montant NUMERIC(14,2) NOT NULL DEFAULT 0,
    semaine INTEGER CHECK(semaine BETWEEN 1 AND 5),
    created_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK(quantite>=0 AND montant>=0)
);
ALTER TABLE variable_paie ADD COLUMN IF NOT EXISTS employee_id INTEGER;
ALTER TABLE variable_paie ADD COLUMN IF NOT EXISTS rubrique_code VARCHAR(20);
ALTER TABLE variable_paie ADD COLUMN IF NOT EXISTS quantite NUMERIC(10,2);
ALTER TABLE variable_paie ADD COLUMN IF NOT EXISTS montant NUMERIC(14,2);
ALTER TABLE variable_paie ADD COLUMN IF NOT EXISTS semaine INTEGER;



CREATE TABLE IF NOT EXISTS bulletin_paie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periode_id INTEGER NOT NULL REFERENCES periode_paie(id) ON DELETE RESTRICT,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    salaire_brut NUMERIC(14,2) NOT NULL,
    cnaps_salarie NUMERIC(14,2) NOT NULL,
    ostie_salarie NUMERIC(14,2) NOT NULL,
    base_imposable NUMERIC(14,2) NOT NULL,
    irsa NUMERIC(14,2) NOT NULL,
    net_a_payer NUMERIC(14,2) NOT NULL,
    UNIQUE(periode_id,employee_id)
);

CREATE TABLE IF NOT EXISTS ligne_bulletin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bulletin_id BIGINT NOT NULL REFERENCES bulletin_paie(id) ON DELETE CASCADE,
    rubrique_code VARCHAR(20) NOT NULL REFERENCES rubrique_paie(code) ON DELETE RESTRICT,
    quantite NUMERIC(10,2),
    taux NUMERIC(14,4),
    montant NUMERIC(14,2) NOT NULL
);


