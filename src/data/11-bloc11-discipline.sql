-- Bloc 11 / Discipline et sanctions
BEGIN;

CREATE TABLE IF NOT EXISTS incident (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  declareur_id VARCHAR(20) REFERENCES users(id),
  objet VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  date_incident DATE NOT NULL,
  statut VARCHAR(30) NOT NULL DEFAULT 'OUVERT',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS procedure_disciplinaire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
  demande_explication TEXT,
  reponse_salarie TEXT,
  date_demande DATE,
  date_limite_reponse DATE,
  decision TEXT,
  statut VARCHAR(30) NOT NULL DEFAULT 'ATTENTE_EXPlication'
);

CREATE TABLE IF NOT EXISTS sanction (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  procedure_id BIGINT NOT NULL REFERENCES procedure_disciplinaire(id) ON DELETE CASCADE,
  type VARCHAR(30) NOT NULL CHECK(type IN ('AVERTISSEMENT','BLAME','MISE_A_PIED','RETENUE_SALAIRE','RETROGRADATION','LICENCEMENT')),
  date_debut DATE,
  date_fin DATE,
  montant NUMERIC(14,2) DEFAULT 0,
  motif TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS document_disciplinaire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id BIGINT REFERENCES incident(id) ON DELETE CASCADE,
  procedure_id BIGINT REFERENCES procedure_disciplinaire(id) ON DELETE CASCADE,
  type VARCHAR(50) NOT NULL,
  storage_path VARCHAR(500) NOT NULL,
  checksum VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_disciplinaire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id VARCHAR(20) REFERENCES users(id),
  action VARCHAR(30) NOT NULL,
  entite VARCHAR(50) NOT NULL,
  entite_id BIGINT,
  details TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_incident_employee ON incident(employee_id);
CREATE INDEX IF NOT EXISTS idx_procedure_incident ON procedure_disciplinaire(incident_id);
COMMIT;
