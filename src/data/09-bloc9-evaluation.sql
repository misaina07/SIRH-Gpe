-- Bloc 9 / Evaluation, competences et formation
BEGIN;

CREATE TABLE IF NOT EXISTS competence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) UNIQUE NOT NULL,
  libelle VARCHAR(150) NOT NULL,
  niveau_max INTEGER NOT NULL DEFAULT 5 CHECK (niveau_max BETWEEN 1 AND 10)
);

CREATE TABLE IF NOT EXISTS employe_competence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  competence_id BIGINT NOT NULL REFERENCES competence(id) ON DELETE CASCADE,
  niveau_attendu INTEGER NOT NULL,
  niveau_acquis INTEGER NOT NULL DEFAULT 0,
  date_evaluation DATE NOT NULL DEFAULT CURRENT_DATE,
  UNIQUE(employee_id, competence_id)
);

CREATE TABLE IF NOT EXISTS objectif (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  periode VARCHAR(20) NOT NULL,
  libelle VARCHAR(200) NOT NULL,
  criteres TEXT,
  ponderation NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (ponderation BETWEEN 0 AND 100),
  statut VARCHAR(20) NOT NULL DEFAULT 'DEFINI'
);

CREATE TABLE IF NOT EXISTS evaluation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  manager_id VARCHAR(20) REFERENCES users(id),
  periode VARCHAR(20) NOT NULL,
  score NUMERIC(5,2),
  commentaire TEXT,
  statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS formation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) UNIQUE NOT NULL,
  titre VARCHAR(200) NOT NULL,
  organisme VARCHAR(150),
  duree_heures NUMERIC(6,2) DEFAULT 0,
  modalite VARCHAR(30) NOT NULL DEFAULT 'PRESENTIEL'
);

CREATE TABLE IF NOT EXISTS inscription_formation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  formation_id BIGINT NOT NULL REFERENCES formation(id) ON DELETE CASCADE,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  date_inscription DATE NOT NULL DEFAULT CURRENT_DATE,
  statut VARCHAR(20) NOT NULL DEFAULT 'INSCRIT',
  attestation_url VARCHAR(500),
  UNIQUE(formation_id, employee_id)
);

CREATE INDEX IF NOT EXISTS idx_employe_competence_employee ON employe_competence(employee_id);
CREATE INDEX IF NOT EXISTS idx_objectif_employee ON objectif(employee_id);
CREATE INDEX IF NOT EXISTS idx_evaluation_employee ON evaluation(employee_id);
CREATE INDEX IF NOT EXISTS idx_inscription_employee ON inscription_formation(employee_id);

