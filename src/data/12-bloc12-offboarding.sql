-- Bloc 12 / Rupture et offboarding
BEGIN;

CREATE TABLE IF NOT EXISTS rupture (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  motif VARCHAR(40) NOT NULL,
  date_notification DATE,
  date_sortie DATE NOT NULL,
  duree_preavis_jours INTEGER NOT NULL DEFAULT 0,
  statut VARCHAR(20) NOT NULL DEFAULT 'EN_COURS',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS solde_tout_compte (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rupture_id BIGINT NOT NULL UNIQUE REFERENCES rupture(id) ON DELETE CASCADE,
  salaire_du NUMERIC(14,2) NOT NULL DEFAULT 0,
  congés_nontpris NUMERIC(14,2) NOT NULL DEFAULT 0,
  indemnité_preavis NUMERIC(14,2) NOT NULL DEFAULT 0,
  indemnité_licenciement NUMERIC(14,2) NOT NULL DEFAULT 0,
  avances NUMERIC(14,2) NOT NULL DEFAULT 0,
  retenues NUMERIC(14,2) NOT NULL DEFAULT 0,
  montant_net NUMERIC(14,2) NOT NULL DEFAULT 0,
  genere_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS materiel_restitution (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rupture_id BIGINT NOT NULL REFERENCES rupture(id) ON DELETE CASCADE,
  designation VARCHAR(150) NOT NULL,
  reference VARCHAR(80),
  statut VARCHAR(20) NOT NULL DEFAULT 'A_RESTITUER',
  date_retour DATE,
  commentaire TEXT
);

CREATE TABLE IF NOT EXISTS archive_offboarding (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  document_type VARCHAR(50) NOT NULL,
  storage_path VARCHAR(500),
  politique_conservation VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rupture_employee ON rupture(employee_id);
CREATE INDEX IF NOT EXISTS idx_materiel_rupture ON materiel_restitution(rupture_id);
COMMIT;
